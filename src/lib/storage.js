import { supabase } from "./supabaseClient";
import { PROPERTY_PHOTO_MAX_BYTES, PROPERTY_PHOTO_MIME_TYPES } from "./propertyPhotoLimits";
import { getDealAttachmentLimit } from "./dealAttachments";

export const uploadAttachment = async (dealId, file, extraMeta = {}) => {
  // 1. Client-side MIME Type Validation (Defense in Depth)
  // Clean MIME type to remove codec parameters, e.g. "audio/webm;codecs=opus" -> "audio/webm"
  const baseType = (file.type || '').split(';')[0].trim().toLowerCase();
  const maxSize = getDealAttachmentLimit(baseType);
  if (!maxSize) {
    throw new Error("Invalid file type. Only JPG, PNG, WEBP, PDF, MP4, and Audio files are allowed.");
  }

  // 2. Client-side Size Validation
  if (file.size > maxSize) {
    throw new Error(`File is too large. Maximum size is ${maxSize / (1024 * 1024)}MB for this file type.`);
  }

  // 3. Generate a secure, unique filename to prevent collisions and directory traversal
  const safeName = file.name.replace(/[^a-zA-Z0-9.\-]/g, '_');
  const uniqueFilename = `${Date.now()}-${Math.random().toString(36).substring(2, 9)}_${safeName}`;
  const filePath = `${dealId}/${uniqueFilename}`;

  // 4. Upload to Supabase Storage
  const { data, error } = await supabase.storage
    .from('chat_attachments')
    .upload(filePath, file, {
      cacheControl: '3600',
      upsert: false
    });

  if (error) {
    throw new Error(error.message || "Failed to upload file to secure storage.");
  }

  // 5. Generate Signed URL for immediate rendering
  // (Assuming RLS prevents direct public access, but signed URLs can be generated by users with SELECT access)
  const { data: urlData, error: urlError } = await supabase.storage
    .from('chat_attachments')
    .createSignedUrl(filePath, 60 * 60 * 24 * 7); // 7 days

  if (urlError) {
    throw new Error("Failed to generate access URL for attachment.");
  }

  return {
    path: filePath,
    url: urlData.signedUrl,
    name: file.name,
    type: baseType || file.type,
    size: file.size,
    isVoiceNote: Boolean(extraMeta.isVoiceNote || baseType.startsWith('audio/')),
    duration: extraMeta.duration || null,
  };
};

export const uploadPropertyPhoto = async (file) => {
  // Client-side quick check
  const baseType = (file.type || '').split(';')[0].trim().toLowerCase();
  if (baseType && !PROPERTY_PHOTO_MIME_TYPES.includes(baseType)) {
    throw new Error("Only JPEG, PNG, and WebP images are supported.");
  }
  if (file.size > PROPERTY_PHOTO_MAX_BYTES) {
    throw new Error("The photo exceeds the 4 MB limit.");
  }

  // A-317: Route upload through authenticated server gate with magic-bytes verification
  const formData = new FormData();
  formData.append("file", file);

  const { data: { session } } = await supabase.auth.getSession().catch(() => ({ data: {} }));
  const token = session?.access_token || "";

  const res = await fetch("/api/storage/upload-photo", {
    method: "POST",
    headers: token ? { Authorization: `Bearer ${token}` } : {},
    body: formData,
  });

  if (!res.ok) {
    const json = await res.json().catch(() => ({}));
    throw new Error(json.error || `Upload failed with status ${res.status}`);
  }

  const json = await res.json();
  return json.url;
};
